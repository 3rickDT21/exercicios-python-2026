

ds=int(input("Digite o dia da semana [EM NÚMERO]"))



if(ds == 1):
        print("Hoje é Domingo!")

elif(ds == 2):
        print("Hoje é Segunda!")

elif(ds == 3):
        print("Hoje é Terça!") 

elif(ds == 4):
        print("Hoje é Quarta!")

elif(ds == 5):
        print("Hoje é Quinta!")

elif(ds == 6):
        print("Hoje é Sexta!")

elif(ds == 7):
        print("Hoje é Sábado!")                   

else:
        print("NÚMERO ÍVALIDO!!!")